package domain

enum class PlcNodeType(val index: Int) {
     CONST_BOOL   (0 ),  // Постоянное логическое значение (0 или 1), используется как источник TRUE/FALSE
     CONST_INT    (1 ),  // Постоянное целое число (уставка, порог, коэффициент)
     DIGITAL_IN   (2 ),  // Дискретный вход (чтение GPIO, кнопки, датчики)
     DIGITAL_OUT  (3 ),  // Дискретный выход (управление GPIO, лампы, реле)
     AND2         (4 ),  // Логическое "И" (выход = 1, если оба входа = 1)
     OR2          (5 ),  // Логическое "ИЛИ" (выход = 1, если хотя бы один вход = 1)
     NOT          (6 ),  // Логическое "НЕ" (инвертирует сигнал: 1→0, 0→1)
     SR           (7 ),  // Защёлка (Set/Reset latch): сохраняет состояние между циклами
     TON          (8 ),  // Таймер на включение (Delay ON): срабатывает после удержания входа заданное время
     TOFF         (9 ),  // Таймер на выключение (Delay OFF): задерживает выключение после отпускания входа
     R_TRIG       (10), // Импульс по фронту (Rising trigger): 1 цикл при переходе 0→1
     F_TRIG       (11), // Импульс по спаду (Falling trigger): 1 цикл при переходе 1→0
     AI_IN        (12), // Аналоговый вход (чтение АЦП, датчиков, потенциометров)
     COMPARE_GT   (13), // Сравнение "БОЛЬШЕ" (A > B)
     COMPARE_LT   (14), // Сравнение "МЕНЬШЕ" (A < B)
     PWM_OUT      (15),  // ШИМ-выход (PWM): формирование аналогового сигнала по коэффициенту заполнения
     MUX2         (16),   // селектор: out = sel ? inA : inB; sel берём из node[paramInt]
     TP           (17), // одноимпульсный таймер: фронт inA -> импульс paramMs
     HYST         (18), // гистерезис: inA(float)->bool; центр=paramFloat; ширина=paramInt/1000
     SCALE        (19), // y=a*x+b; a=paramFloat; b=paramInt/1000
     ADD          (20), // out = inA + inB (float)
     LIMIT        (21),  // clamp: min=paramInt/1000; max=paramMs/1000
     PID          (22),
     ANALOG_AVG   (23),  // сглаживание: y += alpha*(x - y); alpha = paramInt/1000
     RAMP         (24),   // ограничение скорости: |y - prev| <= rate*dt; rate = paramInt/1000 ед/с
     LOG          (25),  // лог: периодически пишет значение входа в plc_log
     AO           (26),  // Аналоговый выход (0..100%) -> ШИМ/DAC по номеру канала
     CTU          (27),  // Счётчик вверх: inA=CLK, inB=RST, paramInt=PV (preset)
     CTD          (28),  // Счётчик вниз: фронт inA (CLK) -> acc--, inB (RST) загружает preset из paramInt
     CTUD         (29),  // Счётчик вверх/вниз: inA = CU, inB = CD (пульсы); out.i = acc
     WINDOW_CHECK (30), // Проверка диапазона: MIN..MAX вокруг paramFloat (центр), ширина paramInt/1000
     SAFE_OUTPUT  (31), // Безопасный выход: нормальное управление + безопасное состояние при аварии
     ALARM_GEN    (32), // Генерация аварийного флага (обёртка над условием)
     ALARM_LATCH  (33), // Защёлкивающаяся авария: держит 1 до квитирования
     HEARTBEAT    (34), // "Сердцебиение": периодическое мигание для проверки живости ПЛК     // Узлы памяти (внутренние регистры)
     MEM_BOOL     (35), // Логическая переменная: чтение/запись bool по индексу
     MEM_INT      (36), // Целочисленная переменная: чтение/запись int32
     MEM_REAL     (37), // Вещественная переменная: чтение/запись float
     FILTER_AVG   (38), // Экспоненциальный фильтр: сглаживание аналогового сигнала
     MATH_OP      (39), // Базовые операции: +, -, *, / над двумя входами
     CONST_FLOAT  (40);  // константа float (уставки, коэффициенты)


     companion object {
          fun get(value: Int) = entries.first { it.index == value }
     }
}